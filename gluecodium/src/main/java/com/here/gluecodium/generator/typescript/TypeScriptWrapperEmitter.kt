    private fun generateIndex(): String {
        val lines = mutableListOf<String>()
        lines += "// Auto-generated by Gluecodium. Do not modify."
        lines += "export { $baseClassName } from './$baseFileName';"
        lines += "export { $errorClassName } from './$errorClassName';"
        for (name in generatedNames.sorted()) {
            lines += "export { $name } from './$name';"
        }
        lines += ""
        return lines.joinToString("\n")
    }

    // ── Type Resolution ───────────────────────────────────────────────────────

    /** Resolves the TS type for a field declaration (uses readonly T[] for lists, T | undefined for nullable). */
    private fun resolveFieldType(typeRef: LimeTypeRef): String {
        val base = resolveType(typeRef)
        if (typeRef.isNullable) return "$base | undefined"
        return base
    }

    private fun resolveType(typeRef: LimeTypeRef): String {
        val actual = typeRef.type.actualType
        val allKnownTypes = structNames + classNames + enumNames
        return when (actual) {
            is LimeBasicType ->
                when (actual.typeId) {
                    LimeBasicType.TypeId.BOOLEAN -> "boolean"
                    LimeBasicType.TypeId.FLOAT, LimeBasicType.TypeId.DOUBLE,
                    LimeBasicType.TypeId.INT8, LimeBasicType.TypeId.INT16,
                    LimeBasicType.TypeId.INT32, LimeBasicType.TypeId.INT64,
                    LimeBasicType.TypeId.UINT8, LimeBasicType.TypeId.UINT16,
                    LimeBasicType.TypeId.UINT32, LimeBasicType.TypeId.UINT64,
                    -> "number"
                    LimeBasicType.TypeId.STRING -> "string"
                    LimeBasicType.TypeId.DURATION -> "number"
                    else -> "any"
                }
            is LimeEnumeration -> {
                val n = nameResolver.resolveName(actual)
                if (n in allKnownTypes) n else "number"
            }
            is LimeStruct -> {
                val n = nameResolver.resolveName(actual)
                if (n in allKnownTypes) n else "any"
            }
            is LimeClass -> {
                val n = nameResolver.resolveName(actual)
                if (n in allKnownTypes) n else "any"
            }
            is LimeList -> {
                val inner = resolveType(actual.elementType)
                if (actual.elementType.type.actualType is LimeList) {
                    "readonly ($inner)[]"
                } else {
                    "readonly $inner[]"
                }
            }
            // A map is exposed idiomatically as a real Map<K, V> (spec task 15.3). Complex key/value
            // types that are not generated wrapper classes fall back to the opaque handle string.
            is LimeMap -> "Map<${resolveMapSideType(actual.keyType)}, ${resolveMapSideType(actual.valueType)}>"
            else -> "any"
        }
    }

    /** TS type for one side (key/value) of a map. Wrapper classes keep their name; scalars stay
     *  number/string/boolean; everything else is an opaque handle string. */
    private fun resolveMapSideType(typeRef: LimeTypeRef): String {
        val allKnownTypes = structNames + classNames + enumNames
        return when (val actual = typeRef.type.actualType) {
            is LimeBasicType ->
                when (actual.typeId) {
                    LimeBasicType.TypeId.BOOLEAN -> "boolean"
                    LimeBasicType.TypeId.STRING -> "string"
                    LimeBasicType.TypeId.DURATION -> "number"
                    LimeBasicType.TypeId.FLOAT, LimeBasicType.TypeId.DOUBLE,
                    LimeBasicType.TypeId.INT8, LimeBasicType.TypeId.INT16,
                    LimeBasicType.TypeId.INT32, LimeBasicType.TypeId.INT64,
                    LimeBasicType.TypeId.UINT8, LimeBasicType.TypeId.UINT16,
                    LimeBasicType.TypeId.UINT32, LimeBasicType.TypeId.UINT64,
                    -> "number"
                    else -> "string"
                }
            is LimeEnumeration -> {
                val n = nameResolver.resolveName(actual)
                if (n in allKnownTypes) n else "number"
            }
            is LimeStruct -> {
                val n = nameResolver.resolveName(actual)
                if (n in allKnownTypes) n else "string"
            }
            is LimeClass -> {
                val n = nameResolver.resolveName(actual)
                if (n in allKnownTypes) n else "string"
            }
            else -> "string"
        }
    }

    private fun resolveReturnType(typeRef: LimeTypeRef): String {
        if (typeRef.type.actualType is LimeBasicType &&
            (typeRef.type.actualType as LimeBasicType).typeId == LimeBasicType.TypeId.VOID
        ) {
            return "void"
        }
        return resolveFieldType(typeRef)
    }

    private fun isCallbackType(typeRef: LimeTypeRef): Boolean = typeRef.type.actualType is LimeLambda

    /**
     * TS type for a method PARAMETER. Mirrors [resolveType] but reflects nullability: a nullable LIME
     * parameter (e.g. `Int?`) becomes `<type> | undefined` so callers can idiomatically pass
     * `undefined`. The marshalling (`marshalToNative`) already collapses `undefined`/`null` to the
     * native `null`, so only the surface type needs widening.
     */
    private fun resolveParamType(typeRef: LimeTypeRef): String {
        val base = resolveType(typeRef)
        return if (typeRef.isNullable && base != "any") "$base | undefined" else base
    }

    private fun resolveAsyncReturnType(typeRef: LimeTypeRef): String {
        val lambda = typeRef.type.actualType as? LimeLambda ?: return "any"
        val params = lambda.parameters
        // The result is resolved only in the non-error branch, where the promisification asserts it
        // non-null (`result!`). The Promise therefore resolves the non-nullable form — an error/result
        // callback never resolves `undefined` alongside a null error. Using resolveType (not
        // resolveFieldType) drops the `| undefined` a nullable result param would otherwise add.
        return if (params.size >= 2) resolveType(params[1].typeRef) else "void"
    }

    private fun buildResultWrapExpr(callbackTypeRef: LimeTypeRef): String {
        val lambda = callbackTypeRef.type.actualType as? LimeLambda ?: return "result"
        if (lambda.parameters.size < 2) return "result"
        val resultParam = lambda.parameters[1]
        val resultName = resultParam.path.name
        val resultTypeRef = resultParam.typeRef
        val actual = resultTypeRef.type.actualType
        val allKnownTypes = structNames + classNames
        return when {
            actual is LimeList -> {
                val elemActual = actual.elementType.type.actualType
                val elemName =
                    when (elemActual) {
                        is LimeStruct -> nameResolver.resolveName(elemActual)
                        is LimeClass -> nameResolver.resolveName(elemActual)
                        else -> null
                    }
                if (elemName != null && elemName in allKnownTypes) {
                    "($resultName ?? []).map((h: string) => $elemName._fromHandle(h))"
                } else {
                    resultName
                }
            }
            actual is LimeStruct -> {
                val n = nameResolver.resolveName(actual)
                if (n in allKnownTypes) "$n._fromHandle($resultName!)" else resultName
            }
            actual is LimeClass -> {
                val n = nameResolver.resolveName(actual)
                if (n in allKnownTypes) "$n._fromHandle($resultName!)" else resultName
            }
            else -> resultName
        }
    }

    private fun getFieldDefault(typeRef: LimeTypeRef): String {
        if (typeRef.isNullable) return "undefined"
        return when (val actual = typeRef.type.actualType) {
            is LimeBasicType ->
                when (actual.typeId) {
                    LimeBasicType.TypeId.BOOLEAN -> "false"
                    LimeBasicType.TypeId.STRING -> "''"
                    else -> "0"
                }
            is LimeEnumeration -> "0"
            is LimeList -> "[]"
            is LimeMap -> "new Map()"
            else -> "undefined as any"
        }
    }

    private fun toCamelCase(snakeCase: String): String {
        val parts = snakeCase.split("_")
        return parts[0] + parts.drop(1).joinToString("") { it.replaceFirstChar { c -> c.uppercase() } }
    }

    private fun shouldExcludeFunction(func: LimeFunction): Boolean {
        if (func.parameters.any { isPlatformSpecificType(it.typeRef.type.actualType) }) return true
        if (func.attributes.have(LimeAttributeType.JAVA, LimeAttributeValueType.SKIP) &&
            func.attributes.have(LimeAttributeType.SWIFT, LimeAttributeValueType.SKIP)
        ) {
            return true
        }
        return false
    }

    private fun isPlatformSpecificType(type: LimeType): Boolean = type.attributes.have(LimeAttributeType.DART, LimeAttributeValueType.SKIP)

    private fun generateBaseClass(): String =
        """
        // Auto-generated by Gluecodium. Do not modify.

        // FinalizationRegistry may not be available in all JS engines (e.g. Hermes).
        // When unavailable, handles must be released manually via dispose().
        const _registry = typeof FinalizationRegistry !== 'undefined'
          ? new FinalizationRegistry<{ handle: string; module: any }>((ref) => {
              try { ref.module.release(ref.handle); } catch (_) {}
